// Command releasectl prepares signed Aster release manifests.
//
// It is run by the release workflow, and can be used locally to rotate the
// update signing key or to inspect a latest.json before publishing it.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"aster/internal/updater"
)

const (
	defaultRepo       = "iMohamedSheta/aster"
	manifestFileName  = "latest.json"
	checksumsFileName = "SHA256SUMS.txt"
)

func main() {
	if err := run(os.Args[1:], os.Stdout, os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "releasectl:", err)
		os.Exit(1)
	}
}

func run(args []string, stdout, stderr io.Writer) error {
	if len(args) == 0 {
		usage(stderr)
		return errors.New("choose a command")
	}
	switch args[0] {
	case "keygen":
		return runKeygen(args[1:], stdout)
	case "publickey":
		return runPublicKey(args[1:], stdout)
	case "manifest":
		return runManifest(args[1:], stdout, stderr)
	case "verify":
		return runVerify(args[1:], stdout)
	case "help", "-h", "--help":
		usage(stdout)
		return nil
	default:
		usage(stderr)
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func usage(w io.Writer) {
	fmt.Fprint(w, `releasectl prepares signed Aster release manifests.

Usage:
  releasectl keygen    [-out update_signing_key] [-public-out update_public_key.txt] [-force]
  releasectl publickey -key update_signing_key [-out update_public_key.txt]
  releasectl manifest  -version 1.2.3 -assets ./dist [options]
  releasectl verify    -manifest latest.json [-key update_public_key.txt]

Manifest options:
  -out latest.json        where to write the manifest
  -notes-url URL          release notes page (default: GitHub tag page)
  -base-url URL           asset download base (default: relative asset names)
  -min-version X.Y.Z      optionally require a minimum installed version
  -published-at RFC3339   override the publication time
  -key FILE               Ed25519 private key used to sign the manifest
  -skip-unknown           ignore files that do not match a release asset name
`)
}

func runKeygen(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("keygen", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	out := fs.String("out", "update_signing_key", "private key file to create")
	publicOut := fs.String("public-out", "", "optional public key file to write")
	force := fs.Bool("force", false, "overwrite an existing private key")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if !*force {
		if _, err := os.Stat(*out); err == nil {
			return fmt.Errorf("%s already exists; pass -force to replace it", *out)
		}
	}
	seed := make([]byte, ed25519.SeedSize)
	if _, err := rand.Read(seed); err != nil {
		return fmt.Errorf("generate signing key: %w", err)
	}
	private := ed25519.NewKeyFromSeed(seed)
	public := private.Public().(ed25519.PublicKey)
	if err := os.WriteFile(*out, []byte(base64.StdEncoding.EncodeToString(seed)+"\n"), 0o600); err != nil {
		return fmt.Errorf("write private key: %w", err)
	}
	encoded := base64.StdEncoding.EncodeToString(public)
	if *publicOut != "" {
		if err := writePublicKeyFile(*publicOut, encoded); err != nil {
			return err
		}
	}
	fmt.Fprintln(stdout, encoded)
	return nil
}

func runPublicKey(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("publickey", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	keyPath := fs.String("key", "", "Ed25519 private key file")
	out := fs.String("out", "", "optional public key file to write")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if strings.TrimSpace(*keyPath) == "" {
		return errors.New("-key is required")
	}
	raw, err := os.ReadFile(*keyPath)
	if err != nil {
		return fmt.Errorf("read private key: %w", err)
	}
	public, err := updater.PublicKeyFromPrivate(string(raw))
	if err != nil {
		return err
	}
	if *out != "" {
		if err := writePublicKeyFile(*out, public); err != nil {
			return err
		}
	}
	fmt.Fprintln(stdout, public)
	return nil
}

func writePublicKeyFile(path, key string) error {
	body := "# Ed25519 public key for update manifests (base64).\n" +
		"# Generated by cmd/releasectl. The matching private key belongs in the\n" +
		"# UPDATE_SIGNING_KEY GitHub Actions secret and must never be committed.\n" +
		key + "\n"
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create public key folder: %w", err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return fmt.Errorf("write public key: %w", err)
	}
	return nil
}

func runManifest(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("manifest", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	version := fs.String("version", "", "release version, with or without a leading v")
	assetsDir := fs.String("assets", "dist", "folder containing the release assets")
	out := fs.String("out", manifestFileName, "manifest path to write")
	notesURL := fs.String("notes-url", "", "release notes URL")
	baseURL := fs.String("base-url", "", "asset download base URL")
	minVersion := fs.String("min-version", "", "optional minimum installed version")
	publishedAt := fs.String("published-at", "", "publication time in RFC3339")
	keyPath := fs.String("key", "", "Ed25519 private key used to sign the manifest")
	skipUnknown := fs.Bool("skip-unknown", false, "ignore files that are not release assets")
	repo := fs.String("repo", defaultRepo, "GitHub repository owner/name")
	if err := fs.Parse(args); err != nil {
		return err
	}
	tag, cleanVersion, err := normalizeVersion(*version)
	if err != nil {
		return err
	}
	if strings.TrimSpace(*notesURL) == "" {
		*notesURL = fmt.Sprintf("https://github.com/%s/releases/tag/%s", *repo, tag)
	}
	if strings.TrimSpace(*publishedAt) == "" {
		*publishedAt = time.Now().UTC().Format(time.RFC3339)
	} else if _, err := time.Parse(time.RFC3339, *publishedAt); err != nil {
		return errors.New("-published-at must be an RFC3339 timestamp")
	}

	manifest, ignored, err := buildManifest(*assetsDir, cleanVersion, *notesURL, *baseURL, *publishedAt, *minVersion, *skipUnknown)
	if err != nil {
		return err
	}
	for _, name := range ignored {
		fmt.Fprintln(stderr, "releasectl: ignoring", name)
	}
	if *keyPath != "" {
		key, err := os.ReadFile(*keyPath)
		if err != nil {
			return fmt.Errorf("read signing key: %w", err)
		}
		if err := manifest.Sign(string(key)); err != nil {
			return err
		}
	}
	if err := manifest.Validate(); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return fmt.Errorf("create manifest folder: %w", err)
	}
	if err := writeManifest(*out, manifest); err != nil {
		return err
	}
	signed := "unsigned"
	if manifest.Signature != "" {
		signed = "signed"
	}
	fmt.Fprintf(stdout, "Wrote %s for %s: %d assets, %s\n", *out, cleanVersion, len(manifest.Assets), signed)
	for _, asset := range manifest.Assets {
		fmt.Fprintf(stdout, "  %-8s %-10s %-10s %s\n", asset.OS, asset.Arch, asset.Kind, asset.Name)
	}
	return nil
}

func runVerify(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("verify", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	manifestPath := fs.String("manifest", manifestFileName, "manifest to verify")
	keyPath := fs.String("key", "", "public key file (base64, comments allowed)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	data, err := os.ReadFile(*manifestPath)
	if err != nil {
		return fmt.Errorf("read manifest: %w", err)
	}
	manifest, err := updater.ParseManifest(data)
	if err != nil {
		return err
	}
	state := "unsigned"
	if strings.TrimSpace(manifest.Signature) != "" {
		state = "signed"
	}
	if *keyPath != "" {
		key, err := readPublicKey(*keyPath)
		if err != nil {
			return err
		}
		if err := manifest.Verify(key); err != nil {
			return err
		}
		state = "signature verified"
	}
	fmt.Fprintf(stdout, "%s: version %s, %d assets, %s\n", *manifestPath, manifest.Version, len(manifest.Assets), state)
	return nil
}

func readPublicKey(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read public key: %w", err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		return line, nil
	}
	return "", errors.New("public key file has no key")
}

func normalizeVersion(value string) (tag, clean string, err error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "", "", errors.New("-version is required")
	}
	clean = strings.TrimPrefix(value, "v")
	clean = strings.TrimPrefix(clean, "V")
	if _, err := updater.ParseSemver(clean); err != nil {
		return "", "", fmt.Errorf("invalid version %q: %w", value, err)
	}
	return "v" + clean, clean, nil
}

// assetRule maps a release file name to its manifest metadata. The naming
// contract is kept in docs/RELEASING.md and in scripts/build-*.
type assetRule struct {
	re      *regexp.Regexp
	os      string
	kind    string
	arch    int // capture group index, 0 means universal
	variant int // capture group index, 0 means none
}

var assetRules = []assetRule{
	{regexp.MustCompile(`^Aster-.+-windows-(amd64|arm64)-setup\.exe$`), "windows", updater.KindInstaller, 1, 0},
	{regexp.MustCompile(`^Aster-.+-windows-(amd64|arm64)-portable\.zip$`), "windows", updater.KindPortable, 1, 0},
	{regexp.MustCompile(`^Aster-.+-darwin-universal\.zip$`), "darwin", updater.KindAppZip, 0, 0},
	{regexp.MustCompile(`^Aster-.+-darwin-universal\.dmg$`), "darwin", updater.KindDMG, 0, 0},
	{regexp.MustCompile(`^Aster-.+-linux-(amd64|arm64)-webkit(40|41)\.tar\.gz$`), "linux", updater.KindTarGz, 1, 2},
	{regexp.MustCompile(`^Aster-.+-linux-(amd64|arm64)-webkit(40|41)\.deb$`), "linux", updater.KindDeb, 1, 2},
}

func classifyAsset(name string) (assetSpec, bool) {
	for _, rule := range assetRules {
		match := rule.re.FindStringSubmatch(name)
		if match == nil {
			continue
		}
		spec := assetSpec{OS: rule.os, Kind: rule.kind, Arch: "universal"}
		if rule.arch > 0 {
			spec.Arch = match[rule.arch]
		}
		if rule.variant > 0 {
			spec.Variant = "webkit" + match[rule.variant]
		}
		return spec, true
	}
	return assetSpec{}, false
}

type assetSpec struct {
	OS      string
	Arch    string
	Kind    string
	Variant string
}

func buildManifest(dir, version, notesURL, baseURL, publishedAt, minVersion string, skipUnknown bool) (*updater.Manifest, []string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, fmt.Errorf("read assets folder: %w", err)
	}
	if strings.TrimSpace(baseURL) != "" {
		baseURL = strings.TrimRight(baseURL, "/") + "/"
	}
	var assets []updater.Asset
	var ignored []string
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if isMetaFile(name) {
			continue
		}
		spec, ok := classifyAsset(name)
		if !ok {
			if skipUnknown {
				ignored = append(ignored, name)
				continue
			}
			return nil, nil, fmt.Errorf("asset %q does not follow the Aster release naming contract", name)
		}
		path := filepath.Join(dir, name)
		size, digest, err := hashFile(path)
		if err != nil {
			return nil, nil, err
		}
		assetURL := url.PathEscape(name)
		if baseURL != "" {
			assetURL = baseURL + assetURL
		}
		assets = append(assets, updater.Asset{
			OS: spec.OS, Arch: spec.Arch, Kind: spec.Kind, Variant: spec.Variant,
			Name: name, URL: assetURL, Size: size, SHA256: digest,
		})
	}
	sort.Slice(assets, func(i, j int) bool {
		if assets[i].OS != assets[j].OS {
			return assets[i].OS < assets[j].OS
		}
		if assets[i].Arch != assets[j].Arch {
			return assets[i].Arch < assets[j].Arch
		}
		if assets[i].Kind != assets[j].Kind {
			return assets[i].Kind < assets[j].Kind
		}
		return assets[i].Name < assets[j].Name
	})
	manifest := &updater.Manifest{
		Schema:         updater.ManifestSchema,
		Version:        version,
		PublishedAt:    publishedAt,
		NotesURL:       notesURL,
		MinimumVersion: strings.TrimSpace(minVersion),
		Assets:         assets,
	}
	if err := manifest.Validate(); err != nil {
		return nil, nil, err
	}
	return manifest, ignored, nil
}

func isMetaFile(name string) bool {
	switch name {
	case manifestFileName, checksumsFileName, "SHA256SUMS", ".DS_Store", "Thumbs.db":
		return true
	}
	return strings.HasSuffix(name, ".sig") || strings.HasSuffix(name, ".sha256")
}

func hashFile(path string) (int64, string, error) {
	file, err := os.Open(path)
	if err != nil {
		return 0, "", fmt.Errorf("open %s: %w", filepath.Base(path), err)
	}
	defer file.Close()
	hash := sha256.New()
	size, err := io.Copy(hash, file)
	if err != nil {
		return 0, "", fmt.Errorf("hash %s: %w", filepath.Base(path), err)
	}
	return size, hex.EncodeToString(hash.Sum(nil)), nil
}

func writeManifest(path string, manifest *updater.Manifest) error {
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return fmt.Errorf("encode manifest: %w", err)
	}
	data = append(data, '\n')
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return fmt.Errorf("write manifest: %w", err)
	}
	return os.Rename(tmp, path)
}
