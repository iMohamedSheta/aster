#!/usr/bin/env node
// Sets the product version everywhere a build reads it.
//
//   node scripts/set-version.mjs 1.2.3
//   ASTER_VERSION=1.2.3 node scripts/set-version.mjs
//
// The release workflow takes the version from the git tag, so wails.json,
// package metadata, the Windows installer and the Go compiler all agree.

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const raw = (process.argv[2] ?? process.env.ASTER_VERSION ?? '').trim()
const version = raw.replace(/^[vV]/, '')

if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`Invalid version ${JSON.stringify(raw)}. Use a semantic version such as 1.2.3 or 1.2.3-beta.1.`)
  process.exit(1)
}

const core = version.split('+')[0].split('-')[0]
const quad = `${core}.0`

async function readJSON(path) {
  return JSON.parse(await readFile(join(root, path), 'utf8'))
}

async function writeJSON(path, value) {
  await writeFile(join(root, path), `${JSON.stringify(value, null, 2)}\n`)
}

const wails = await readJSON('wails.json')
wails.info = { ...wails.info, productVersion: version }
await writeJSON('wails.json', wails)

const pkg = await readJSON('frontend/package.json')
pkg.version = version
await writeJSON('frontend/package.json', pkg)

const lock = await readJSON('frontend/package-lock.json')
lock.version = version
if (lock.packages && lock.packages['']) lock.packages[''].version = version
await writeJSON('frontend/package-lock.json', lock)

const nsh = `; Generated by scripts/set-version.mjs. The committed values keep local
; installer builds working before the first release job runs.
!ifndef ASTER_VERSION
  !define ASTER_VERSION "${version}"
!endif
!ifndef ASTER_VERSION_QUAD
  !define ASTER_VERSION_QUAD "${quad}"
!endif
`
const nshPath = join(root, 'build/windows/installer/version.nsh')
await mkdir(dirname(nshPath), { recursive: true })
await writeFile(nshPath, nsh)

console.log(`Aster version set to ${version} (${quad})`)
